"""Разбор коротких голосовых ответов пользователя."""

import re

_YES = {"да", "подтверждаю", "давай", "выполняй", "конечно", "ага"}
_NO = {"нет", "не", "отмена", "отменить", "стоп", "отставить", "отбой"}


def is_confirmation(text: str) -> bool:
    """Да — только если есть согласие и нет ни одного слова отказа: при сомнении не выполняем."""
    words = set(re.findall(r"\w+", text.lower()))
    return bool(words & _YES) and not words & _NO
